-- Run this once in Supabase Dashboard > SQL Editor.
-- It creates the shared sticky-note board and limits every operation to the
-- signed-in user's couple.

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  couple_id uuid not null references public.couples(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 500),
  color text not null default 'pink' check (color in ('yellow', 'pink', 'cyan', 'lilac')),
  created_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists notes_couple_updated_idx
  on public.notes (couple_id, updated_at desc);

alter table public.notes enable row level security;

drop policy if exists "couple members can read notes" on public.notes;
create policy "couple members can read notes"
on public.notes for select
to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = notes.couple_id
  )
);

drop policy if exists "couple members can create notes" on public.notes;
create policy "couple members can create notes"
on public.notes for insert
to authenticated
with check (
  created_by = auth.uid()
  and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = notes.couple_id
  )
);

drop policy if exists "couple members can update notes" on public.notes;
create policy "couple members can update notes"
on public.notes for update
to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = notes.couple_id
  )
)
with check (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = notes.couple_id
  )
);

drop policy if exists "couple members can delete notes" on public.notes;
create policy "couple members can delete notes"
on public.notes for delete
to authenticated
using (
  exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = notes.couple_id
  )
);

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'notes'
  ) then
    alter publication supabase_realtime add table public.notes;
  end if;
end $$;
