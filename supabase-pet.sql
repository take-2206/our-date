-- Shared pet reactions. Run this once in Supabase Dashboard > SQL Editor.
-- Each member has one persistent bubble; both members can see both bubbles.
create table if not exists public.pet_reactions (
  id bigint generated by default as identity primary key,
  couple_id uuid not null references public.couples(id) on delete cascade,
  sender_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  emoji text not null check (emoji in ('❤️', '😂', '🥺', '😴', '✨', '😡', '💔')),
  created_at timestamptz not null default now()
);

alter table public.pet_reactions drop constraint if exists pet_reactions_emoji_check;
alter table public.pet_reactions
  add constraint pet_reactions_emoji_check
  check (emoji in ('❤️', '😂', '🥺', '😴', '✨', '😡', '💔'));

create index if not exists pet_reactions_couple_created_idx
  on public.pet_reactions (couple_id, created_at desc);

-- If an earlier version stored a reaction history, keep each member's latest icon.
delete from public.pet_reactions older
using public.pet_reactions newer
where older.couple_id = newer.couple_id
  and older.sender_id = newer.sender_id
  and (older.created_at, older.id) < (newer.created_at, newer.id);

create unique index if not exists pet_reactions_one_bubble_per_member_idx
  on public.pet_reactions (couple_id, sender_id);

alter table public.pet_reactions enable row level security;
grant select, insert, update, delete on public.pet_reactions to authenticated;
grant usage, select on sequence public.pet_reactions_id_seq to authenticated;

drop policy if exists "Couple members can read pet reactions" on public.pet_reactions;
create policy "Couple members can read pet reactions"
  on public.pet_reactions for select to authenticated
  using (exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = pet_reactions.couple_id
  ));

drop policy if exists "Couple members can add their own pet reactions" on public.pet_reactions;
create policy "Couple members can add their own pet reactions"
  on public.pet_reactions for insert to authenticated
  with check (sender_id = auth.uid() and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = pet_reactions.couple_id
  ));

drop policy if exists "Members can change their own pet bubble" on public.pet_reactions;
create policy "Members can change their own pet bubble"
  on public.pet_reactions for update to authenticated
  using (sender_id = auth.uid() and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = pet_reactions.couple_id
  ))
  with check (sender_id = auth.uid() and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = pet_reactions.couple_id
  ));

drop policy if exists "Members can remove their own pet bubble" on public.pet_reactions;
create policy "Members can remove their own pet bubble"
  on public.pet_reactions for delete to authenticated
  using (sender_id = auth.uid() and exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.couple_id = pet_reactions.couple_id
  ));

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'pet_reactions'
  ) then
    alter publication supabase_realtime add table public.pet_reactions;
  end if;
end $$;
